from __future__ import annotations

from abc import ABC, abstractmethod
from pathlib import Path

from pydantic import BaseModel, ConfigDict, Field

from ctf_architect.core.strategy import DeploymentStrategy


class DeploymentActionResult(BaseModel):
    """Represents the result of applying a deployment action.

    Attributes:
        name (str): An identifier for the action result.
        action (DeploymentAction): The deployment action that was applied.
        success (bool): Whether the action was successfully applied.
        message (str, optional): An optional message providing additional information about the result.
        prerequisite_results (list[DeploymentActionResult]): Results of prerequisite actions.
        subaction_results (list[DeploymentActionResult]): Results of any sub-actions that were part of this action.
    """

    model_config = ConfigDict(arbitrary_types_allowed=True)

    action: DeploymentAction
    success: bool
    message: str | None = None
    prerequisite_results: list[DeploymentActionResult] = Field(default_factory=list)
    subaction_results: list[DeploymentActionResult] = Field(default_factory=list)

    @property
    def name(self) -> str:
        return self.action.name

    @property
    def msg_string(self) -> str:
        status = "SUCCESS" if self.success else "FAILURE"
        return f"{self.name}: {status} - {self.message or 'No message'}"


class DeploymentAction(BaseModel, ABC):
    """Base class for deployment actions.

    Actions represent a requested output from a deployment strategy.

    Attributes:
        name (str): An identifier for the action.
        strategy (DeploymentStrategy): The deployment strategy that generated the action.
        description (str, optional): A human-readable description of the action.
        prerequisites (list[DeploymentAction], optional): A list of actions that must be completed before this action can be applied.
        subactions (list[DeploymentAction], optional): A list of actions grouped under a composite action.
    """

    model_config = ConfigDict(arbitrary_types_allowed=True)

    name: str
    strategy: DeploymentStrategy
    description: str | None = None
    prerequisites: list[DeploymentAction] = Field(default_factory=list)
    subactions: list[DeploymentAction] = Field(default_factory=list)

    @property
    def is_composite(self) -> bool:
        """Check if the action is a composite action (i.e., has subactions)."""
        return len(self.subactions) > 0

    @property
    def msg_string(self) -> str:
        return f"{self.name}: {self.description or 'No description'}"

    @abstractmethod
    def apply(
        self,
        prerequisite_results: list[DeploymentActionResult] | None = None,
        subaction_results: list[DeploymentActionResult] | None = None,
    ) -> DeploymentActionResult:
        """Apply the action."""
        pass


class CreateFileAction(DeploymentAction):
    """Represents a file output action generated by a deployment strategy.

    Attributes:
        target_path (Path): The target path where the file should be placed.
        temp_path (Path, optional): The temporary path where the file is initially created.
    """

    target_path: Path
    content: str | bytes

    @property
    def msg_string(self) -> str:
        return f"{self.name}: Create file at {self.target_path.as_posix()}"

    def apply(self, *args, **kwargs) -> DeploymentActionResult:
        try:
            self.target_path.parent.mkdir(parents=True, exist_ok=True)
            mode = "wb" if isinstance(self.content, bytes) else "w"
            with open(self.target_path, mode) as f:
                f.write(self.content)
            return DeploymentActionResult(
                action=self,
                success=True,
                message=f"File created at {self.target_path.as_posix()}",
            )
        except Exception as e:
            return DeploymentActionResult(
                action=self,
                success=False,
                message=f"Failed to create file at {self.target_path.as_posix()}: {e}",
            )


class UpdateFileAction(DeploymentAction):
    """Represents a file update action generated by a deployment strategy.

    Attributes:
        target_path (Path): The target path where the file should be updated.
        old_content (str | bytes): The existing content of the file.
        new_content (str | bytes): The new content to update the file with.
    """

    target_path: Path
    old_content: str | bytes
    new_content: str | bytes

    @property
    def msg_string(self) -> str:
        return f"{self.name}: Update file at {self.target_path.as_posix()}"

    def apply(self, *args, **kwargs) -> DeploymentActionResult:
        try:
            if self.old_content != self.new_content:
                mode = "wb" if isinstance(self.new_content, bytes) else "w"
                with open(self.target_path, mode) as f:
                    f.write(self.new_content)
                return DeploymentActionResult(
                    action=self,
                    success=True,
                    message=f"File updated at {self.target_path.as_posix()}",
                )
            else:
                return DeploymentActionResult(
                    action=self,
                    success=True,
                    message=f"No changes made to {self.target_path.as_posix()}",
                )
        except Exception as e:
            return DeploymentActionResult(
                action=self,
                success=False,
                message=f"Failed to update file at {self.target_path.as_posix()}: {e}",
            )
